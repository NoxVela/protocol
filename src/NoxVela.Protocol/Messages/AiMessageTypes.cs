using System;

namespace NoxVela.Protocol.Messages;

/// <summary>
/// Defines message type constants for AI and RAG subsystem communications.
/// </summary>
public class AiMessageTypes
{
    /// <summary>
    /// Instruction dispatched to start an NLP batch embedding or run finalization.
    /// </summary>
    public const string START_EMBEDDING = "start_embedding";

    /// <summary>
    /// Progress update and status report frame emitted by the continuous embedder worker.
    /// </summary>
    public const string EMBEDDING_STATUS = "embedding_status";

    /// <summary>
    /// Command triggering Graph Neural Network (GNN) topological evaluation post AST analysis.
    /// </summary>
    public const string FINALIZE_RUN = "finalize_run";

    /// <summary>
    /// User query message dispatched to the AI assistant.
    /// </summary>
    public const string CHAT_MESSAGE = "chat_message";

    /// <summary>
    /// Retrieved semantic and topological context payload returned prior to chunk streaming.
    /// </summary>
    public const string RAG_CONTEXT = "rag_context";

    /// <summary>
    /// Streaming text chunk generated by the LLM response generator.
    /// </summary>
    public const string CHUNK_RESPONSE = "chunk_response";

    /// <summary>
    /// Signal indicating completion of LLM response streaming.
    /// </summary>
    public const string CHUNK_RESPONSE_COMPLETE = "chunk_response_complete";
}
